import streamlit as st 
import pandas as pd 
import matplotlib.pyplot as plt
st.title('Retail Sales Dashboard')
kpis = pd.read_csv('outputs/kpis.csv')
col1, col2, col3 = st.columns(3)
col1.metric('Total revenue', f"£{kpis['Revenue'][0]:,.0f}")
col2.metric('Customers', f"{kpis['Customers'][0]:,}")
col3.metric('Orders', f"{kpis['Orders'][0]:,}")
st.header('Monthly Revenue')
monthly = pd.read_csv('outputs/monthly_revenue.csv', index_col=0)
st.line_chart(monthly)
st.header('Top 10 products')
top_products= pd.read_csv('outputs/top_products.csv',index_col=0)
st.dataframe(top_products[['Description','Revenue']])
st.header('Top countries outside UK')
countries = pd.read_csv('outputs/countries.csv',index_col=0)
fig, ax = plt.subplots()
countries['Revenue'].plot(kind='bar', ax=ax)
ax.set_ylabel('Revenue (£)')
ax.set_xlabel('Country')
st.pyplot(fig)
st.dataframe(countries)
st.header('Churned customers to win back')
churned = pd.read_csv('outputs/churned.csv',index_col=0)
st.dataframe(churned[['Revenue','Orders','DaysSince']])
